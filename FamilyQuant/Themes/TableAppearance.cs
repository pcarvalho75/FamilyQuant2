using System;
using System.Collections;
using System.Collections.Generic;
using System.Collections.Specialized;
using System.ComponentModel;
using System.Linq;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Controls.Primitives;
using System.Windows.Data;

namespace FamilyQuant.Themes
{
    /// <summary>Presentation only: keeps bindings, commands, row flags and source values intact.</summary>
    public static class TableAppearance
    {
        public static readonly DependencyProperty EnabledProperty = DependencyProperty.RegisterAttached(
            "Enabled", typeof(bool), typeof(TableAppearance), new PropertyMetadata(false, Changed));
        private static readonly DependencyProperty StateProperty = DependencyProperty.RegisterAttached(
            "State", typeof(State), typeof(TableAppearance));
        public static readonly DependencyProperty NumericProperty = DependencyProperty.RegisterAttached(
            "Numeric", typeof(bool), typeof(TableAppearance), new PropertyMetadata(false));
        public static readonly DependencyProperty FullTextPathProperty = DependencyProperty.RegisterAttached(
            "FullTextPath", typeof(string), typeof(TableAppearance), new PropertyMetadata(null));
        public static string? GetFullTextPath(DependencyObject target) => (string?)target.GetValue(FullTextPathProperty);
        public static void SetFullTextPath(DependencyObject target, string? value) => target.SetValue(FullTextPathProperty, value);
        public static bool GetEnabled(DependencyObject target) => (bool)target.GetValue(EnabledProperty);
        public static void SetEnabled(DependencyObject target, bool value) => target.SetValue(EnabledProperty, value);
        public static bool GetNumeric(DependencyObject target) => (bool)target.GetValue(NumericProperty);
        public static void SetNumeric(DependencyObject target, bool value) => target.SetValue(NumericProperty, value);
        private static void Changed(DependencyObject target, DependencyPropertyChangedEventArgs e)
        {
            if (target is not DataGrid grid) return;
            (grid.GetValue(StateProperty) as State)?.Dispose();
            grid.SetValue(StateProperty, (bool)e.NewValue ? new State(grid) : null);
        }

        private sealed class State : IDisposable
        {
            private readonly DataGrid grid;
            private readonly Dictionary<DataGridColumn, (Style? Original, Style Applied, bool Numeric)> headers = new();
            private readonly Dictionary<DataGridTextColumn, Style?> originals = new();
            private readonly DependencyPropertyDescriptor headerProperty = DependencyPropertyDescriptor.FromProperty(
                DataGridColumn.HeaderStyleProperty, typeof(DataGridColumn));
            private readonly DependencyPropertyDescriptor sourceProperty = DependencyPropertyDescriptor.FromProperty(
                ItemsControl.ItemsSourceProperty, typeof(DataGrid));
            private Style? originalRows, appliedRows;
            private bool attached, writing;

            internal State(DataGrid grid)
            {
                this.grid = grid;
                grid.Loaded += Loaded; grid.Unloaded += Unloaded;
                if (grid.IsLoaded) Attach();
            }
            private void Loaded(object sender, RoutedEventArgs e) => Attach();
            private void Unloaded(object sender, RoutedEventArgs e) => Detach();
            private void Attach()
            {
                if (attached) return;
                attached = true;
                grid.SetResourceReference(Control.BackgroundProperty, "SurfaceBrush");
                grid.SetResourceReference(Control.ForegroundProperty, "TextBrush");
                // Parent local row brushes outrank row triggers during DataGrid's property transfer.
                // Use the shared style values so hover and selection retain their precedence.
                grid.ClearValue(DataGrid.RowBackgroundProperty);
                grid.ClearValue(DataGrid.AlternatingRowBackgroundProperty);
                grid.GridLinesVisibility = DataGridGridLinesVisibility.None;
                grid.EnableRowVirtualization = true; grid.EnableColumnVirtualization = true;
                VirtualizingPanel.SetVirtualizationMode(grid, VirtualizationMode.Recycling);
                ((INotifyCollectionChanged)grid.Columns).CollectionChanged += ColumnsChanged;
                grid.AutoGeneratedColumns += Generated;
                sourceProperty.AddValueChanged(grid, Generated);
                originalRows = grid.RowStyle;
                if (originalRows != null)
                {
                    appliedRows = new Style(typeof(DataGridRow), originalRows);
                    var hover = new Trigger { Property = UIElement.IsMouseOverProperty, Value = true };
                    hover.Setters.Add(new Setter(Control.BackgroundProperty, new DynamicResourceExtension("HoverBrush")));
                    var selected = new Trigger { Property = DataGridRow.IsSelectedProperty, Value = true };
                    selected.Setters.Add(new Setter(Control.BackgroundProperty, new DynamicResourceExtension("SelectionBrush")));
                    appliedRows.Triggers.Add(hover); appliedRows.Triggers.Add(selected);
                    grid.RowStyle = appliedRows;
                }
                Refresh();
            }
            private void Generated(object? sender, EventArgs e) => Refresh();
            private void ColumnsChanged(object? sender, NotifyCollectionChangedEventArgs e) => Refresh();
            private void Refresh()
            {
                foreach (var old in headers.Keys.Where(c => !grid.Columns.Contains(c)).ToArray()) Unwatch(old);
                foreach (DataGridColumn column in grid.Columns)
                {
                    if (!headers.ContainsKey(column)) headerProperty.AddValueChanged(column, HeaderChanged);
                    Decorate(column);
                }
            }
            private void HeaderChanged(object? sender, EventArgs e)
            {
                if (!writing && sender is DataGridColumn column) Decorate(column);
            }
            private void Decorate(DataGridColumn column)
            {
                bool numeric = IsNumeric(grid, column);
                bool same = headers.TryGetValue(column, out var previous) && ReferenceEquals(column.HeaderStyle, previous.Applied);
                if (same && previous.Numeric == numeric) return;
                Style? original = same ? previous.Original : column.HeaderStyle;
                var header = new Style(typeof(DataGridColumnHeader), original
                    ?? Application.Current.TryFindResource(typeof(DataGridColumnHeader)) as Style);
                // Keep direct tooltip setters discoverable to the existing accessibility checks.
                if (original != null)
                    foreach (Setter setter in original.Setters.OfType<Setter>()) header.Setters.Add(setter);
                header.Setters.Add(new Setter(Control.BackgroundProperty, new DynamicResourceExtension("SubtleBrush")));
                header.Setters.Add(new Setter(Control.ForegroundProperty, new DynamicResourceExtension("MutedBrush")));
                header.Setters.Add(new Setter(Control.BorderThicknessProperty, new Thickness(0)));
                header.Setters.Add(new Setter(Control.PaddingProperty, new DynamicResourceExtension("TableHeaderPadding")));
                if (numeric) header.Setters.Add(new Setter(Control.HorizontalContentAlignmentProperty, HorizontalAlignment.Right));
                headers[column] = (original, header, numeric);
                writing = true;
                try { column.HeaderStyle = header; }
                finally { writing = false; }
                if (column is DataGridTextColumn text)
                {
                    if (!originals.TryGetValue(text, out var textOriginal)) originals[text] = textOriginal = text.ElementStyle;
                    var style = new Style(typeof(TextBlock), textOriginal ?? DataGridTextColumn.DefaultElementStyle);
                    style.Setters.Add(new Setter(TextBlock.TextTrimmingProperty, TextTrimming.CharacterEllipsis));
                    style.Setters.Add(new Setter(TextBlock.TextWrappingProperty, TextWrapping.NoWrap));
                    style.Setters.Add(new Setter(FrameworkElement.ToolTipProperty,
                        GetFullTextPath(column) is string path ? new Binding(path)
                            : new Binding(nameof(TextBlock.Text)) { RelativeSource = RelativeSource.Self }));
                    if (numeric) style.Setters.Add(new Setter(TextBlock.TextAlignmentProperty, TextAlignment.Right));
                    text.ElementStyle = style;
                }
            }
            private void Unwatch(DataGridColumn column)
            {
                headerProperty.RemoveValueChanged(column, HeaderChanged);
                if (headers.Remove(column, out var entry) && ReferenceEquals(column.HeaderStyle, entry.Applied)) column.HeaderStyle = entry.Original;
                if (column is DataGridTextColumn text && originals.Remove(text, out var original)) text.ElementStyle = original;
            }
            private void Detach()
            {
                if (!attached) return;
                attached = false;
                ((INotifyCollectionChanged)grid.Columns).CollectionChanged -= ColumnsChanged;
                grid.AutoGeneratedColumns -= Generated;
                sourceProperty.RemoveValueChanged(grid, Generated);
                foreach (var column in headers.Keys.ToArray()) Unwatch(column);
                if (ReferenceEquals(grid.RowStyle, appliedRows)) grid.RowStyle = originalRows;
                originalRows = appliedRows = null;
            }
            public void Dispose() { Detach(); grid.Loaded -= Loaded; grid.Unloaded -= Unloaded; }
        }

        private static bool IsNumeric(DataGrid grid, DataGridColumn column)
        {
            if (GetNumeric(column)) return true;
            if (column is not DataGridBoundColumn bound || bound.Binding is not Binding binding) return false;
            object? source = grid.ItemsSource;
            if (source is ICollectionView view) source = view.SourceCollection;
            Type? type = source == null ? null : source.GetType().GetInterfaces().Concat(new[] { source.GetType() })
                .FirstOrDefault(t => t.IsGenericType && t.GetGenericTypeDefinition() == typeof(IEnumerable<>))?.GetGenericArguments()[0];
            type ??= grid.Items.OfType<object>().FirstOrDefault()?.GetType();
            foreach (string part in (binding.Path?.Path ?? "").Split('.', StringSplitOptions.RemoveEmptyEntries))
                type = type?.GetProperty(part)?.PropertyType;
            if (type == null || type.IsEnum) return false;
            type = Nullable.GetUnderlyingType(type) ?? type;
            if (type.IsEnum) return false;
            return Type.GetTypeCode(type) is TypeCode.Byte or TypeCode.SByte or TypeCode.Int16 or TypeCode.UInt16
                or TypeCode.Int32 or TypeCode.UInt32 or TypeCode.Int64 or TypeCode.UInt64
                or TypeCode.Single or TypeCode.Double or TypeCode.Decimal;
        }
    }
}
