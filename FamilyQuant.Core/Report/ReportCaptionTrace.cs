using FamilyQuant.Report.Captions;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;

namespace FamilyQuant.Report;

/// <summary>Audit cells for every generated caption number. The displayed lexeme is formatted by
/// the same caption builder used in Word; the unrounded native value remains beside it.</summary>
public static class ReportCaptionTrace
{
    public static IReadOnlyList<ReportSupplementSheet> Build(ReportDocument document,
        IReadOnlyDictionary<string, FigureCaptionInput> bindings)
    {
        var result = new List<ReportSupplementSheet>();
        foreach (var section in document.Sections)
        {
            foreach (var figure in section.Blocks.OfType<ReportFigure>())
            {
                var rows = new List<IReadOnlyList<string>>();
                if (!bindings.TryGetValue(figure.Id, out var input))
                    throw new InvalidOperationException("A figure has no caption trace binding: " + figure.Id);
                foreach (var fact in input.Numbers)
                    rows.Add(new[] { figure.Id, figure.Title, fact.Label, fact.Value.ToString("R", CultureInfo.InvariantCulture),
                        ReportCaptionBuilder.Number(fact.Value, format: fact.Format), fact.Unit });
                if (rows.Count == 0) continue;
                string id = figure.Id;
                var table = new ReportTable(id, figure.Title + " - caption number trace",
                new[] { "Figure ID", "Figure", "Fact", "Native value", "Displayed value", "Unit" }, rows,
                "The displayed value is generated by the same invariant formatter as the Word caption. Native values are retained without display rounding.");
                string suffix = Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(id)))[..6];
                result.Add(new(id, section.Id, "Caption_facts_" + suffix, table));
            }
        }
        return result;
    }
}
